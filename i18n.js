  let current = 'zh';

  function available() {
    return Object.keys(DICT);
  }

  // 浏览器语言只用来猜首次的默认值，之后以用户在设置里的选择为准
  function detect() {
    try {
      const l = String(chrome.i18n.getUILanguage() || '').toLowerCase();
      if (l.indexOf('zh') === 0) return 'zh';
      if (DICT[l.slice(0, 2)]) return l.slice(0, 2);
    } catch (e) {}
    return 'en';
  }

  function setLang(lang) {
    current = DICT[lang] ? lang : detect();
    return current;
  }

  function getLang() {
    return current;
  }

  function t(key, vars) {
    const table = DICT[current] || DICT.zh;
    // 某个语言漏了某条就回落到中文，再不行就把键名显示出来（方便发现漏翻）
    let s = table[key];
    if (s == null) s = DICT.zh[key];
    if (s == null) return key;
    if (vars) {
      for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
    }
    return s;
  }

  // 把 HTML 里标了 data-i18n 的地方填上文字
  function applyDom(scope) {
    const el = scope || document;
    el.querySelectorAll('[data-i18n]').forEach((n) => {
      n.textContent = t(n.dataset.i18n);
    });
    el.querySelectorAll('[data-i18n-ph]').forEach((n) => {
      n.placeholder = t(n.dataset.i18nPh);
    });
    el.querySelectorAll('[data-i18n-title]').forEach((n) => {
      n.title = t(n.dataset.i18nTitle);
    });
  }

  root.YTI18N = { t, setLang, getLang, detect, applyDom, available };
